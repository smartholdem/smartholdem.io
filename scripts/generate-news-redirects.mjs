#!/usr/bin/env node
// Generates an nginx 301 redirect map for legacy news id URLs -> slug URLs,
// covering all 18 locales. Output: nginx/news-redirects.map (+ example conf).
//
// Usage: node scripts/generate-news-redirects.mjs   (or: yarn news:redirects)
// Data source: live Strapi first, baked snapshot (assets/news-snapshot.json)
// as offline fallback — same policy as the prerender hook.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildNewsSlugs } from '../server/utils/newsSlug.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

// Non-default locale prefixes (default `en` lives at the root)
const LOCALES = ['ru', 'zh', 'id', 'ko', 'th', 'es', 'vi', 'fr', 'de', 'kk', 'pt', 'uz', 'mn', 'ja', 'sw', 'ar', 'hi']

async function loadItems() {
  try {
    const res = await fetch('https://news.smartholdem.io/api/sthnews?pagination[pageSize]=200&sort=date:desc')
    const json = await res.json()
    if (json?.data?.length) return json.data
  } catch (e) {
    console.warn('[news-redirects] live fetch failed, using baked snapshot:', e?.message || e)
  }
  const raw = await readFile(resolve(ROOT, 'assets/news-snapshot.json'), 'utf-8')
  const snap = JSON.parse(raw)
  return Array.isArray(snap) ? snap : []
}

const items = await loadItems()
const { idToSlug } = buildNewsSlugs(items)

const lines = []
for (const [id, slug] of [...idToSlug.entries()].sort((a, b) => Number(a[0]) - Number(b[0]))) {
  lines.push(`/news/${id} /news/${slug};`)
  for (const lc of LOCALES) lines.push(`/${lc}/news/${id} /${lc}/news/${slug};`)
}

const mapFile = `# Auto-generated by scripts/generate-news-redirects.mjs — do not edit by hand.
# Legacy news id URLs -> canonical slug URLs (${idToSlug.size} articles x ${LOCALES.length + 1} locales).
${lines.join('\n')}
`

const exampleConf = `# HOW TO USE (nginx):
#
# 1) In the http {} block:
#
#    map_hash_max_size 8192;
#    map_hash_bucket_size 128;
#    map $uri $news_redirect {
#        default "";
#        include /etc/nginx/news-redirects.map;
#    }
#
# 2) In the server {} block serving smartholdem.io (BEFORE other location rules):
#
#    if ($news_redirect) {
#        return 301 $news_redirect;
#    }
#
# 3) Copy news-redirects.map to /etc/nginx/ and reload:  nginx -s reload
#
# Regenerate the map after publishing news:  yarn news:redirects
`

await mkdir(resolve(ROOT, 'nginx'), { recursive: true })
await writeFile(resolve(ROOT, 'nginx/news-redirects.map'), mapFile, 'utf-8')
await writeFile(resolve(ROOT, 'nginx/README.conf.txt'), exampleConf, 'utf-8')
console.log(`[news-redirects] wrote nginx/news-redirects.map (${lines.length} redirects for ${idToSlug.size} articles)`)
